// ═══════════════════ УТИЛИТЫ ═══════════════════
function normAngle(a) {
  while (a > Math.PI) a -= Math.PI * 2;
  while (a < -Math.PI) a += Math.PI * 2;
  return a;
}
function dist(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}
function rnd(a, b) {
  return a + Math.random() * (b - a);
}
function rndInt(a, b) {
  return Math.floor(rnd(a, b + 1));
}
function pickRandom(arr) {
  return arr[rndInt(0, arr.length - 1)];
}

