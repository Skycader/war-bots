// Нормализация угла: радианы → градусы 0..360
// Система координат canvas: 0=вправо, 90=вниз, 180=влево, 270=вверх
// Именно эти значения и отдаём в Bot API — без инверсии, round-trip безопасно
function normDeg(rad) {
  let d = (rad * 180) / Math.PI;
  d = d % 360;
  if (d < 0) d += 360;
  return d;
}
// Обратное: градусы → радианы (без инверсии)
function degToRad(deg) {
  return (deg * Math.PI) / 180;
}

